CREATE TABLE routes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origin_id BIGINT NOT NULL,
    destination_id BIGINT NOT NULL,
    estimated_duration_minutes INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL,
    CONSTRAINT fk_routes_origin FOREIGN KEY (origin_id) REFERENCES locations(id),
    CONSTRAINT fk_routes_destination FOREIGN KEY (destination_id) REFERENCES locations(id),
    CONSTRAINT chk_routes_different_locations CHECK (origin_id <> destination_id),
    CONSTRAINT chk_routes_duration CHECK (estimated_duration_minutes > 0),
    CONSTRAINT ck_routes_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);
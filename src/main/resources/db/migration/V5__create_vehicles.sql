CREATE TABLE vehicles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operator_id BIGINT NOT NULL,
    license_plate VARCHAR(20) NOT NULL,
    vehicle_type VARCHAR(50) NOT NULL,
    seat_capacity INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_vehicles_license_plate UNIQUE (license_plate),
    CONSTRAINT fk_vehicles_operator FOREIGN KEY (operator_id) REFERENCES bus_operators(id),
    CONSTRAINT chk_vehicles_seat_capacity CHECK (seat_capacity > 0),
    CONSTRAINT ck_vehicles_license_plate CHECK (btrim(license_plate) <> ''),
    CONSTRAINT ck_vehicles_type CHECK (btrim(vehicle_type) <> ''),
    CONSTRAINT ck_vehicles_status CHECK (status IN ('ACTIVE', 'INACTIVE', 'MAINTENANCE'))
);